"""Builds the admin website's /terms and /privacy pages from the app's text.

The Terms and Privacy Policy are written once, in lib/l10n/app_en.arb and
app_fil.arb (termsS* / privacyS*). This script turns them into
admin/resources/views/legal/{terms,privacy}.blade.php so the website shows
exactly what the app shows, in English (default) and Filipino (?lang=fil).
Sections listed in LegalConfig.ownerReviewSections get the "draft" note.

    python3 scripts/gen_legal_pages.py          # rewrite the pages
    python3 scripts/gen_legal_pages.py --check  # fail if they are out of date (CI)
"""
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ARB = {"en": ROOT / "lib/l10n/app_en.arb", "fil": ROOT / "lib/l10n/app_fil.arb"}
CONFIG = ROOT / "lib/core/config/legal_config.dart"
OUT = ROOT / "admin/resources/views/legal"

DOCS = {
    # name: (arb prefix, title key, route of the other page, title key of the other page)
    "terms": ("termsS", "legalTermsTitle", "legal.privacy", "legalPrivacyTitle"),
    "privacy": ("privacyS", "legalPrivacyTitle", "legal.terms", "legalTermsTitle"),
}
# Website-only words (the app has its own back button and language setting).
UI = {
    "en": {"back": "Go back", "switch": "Filipino", "switch_lang": "fil"},
    "fil": {"back": "Bumalik", "switch": "English", "switch_lang": "en"},
}


def esc(text: str) -> str:
    # Blade would read "@word" as a directive and "{{" as an echo; escape both.
    return html.escape(text).replace("@", "&#64;").replace("{", "&#123;")


def body_html(body: str) -> str:
    lines = body.split("\n")
    if all(l.startswith("• ") for l in lines):
        return "<ul>" + "".join(f"<li>{esc(l[2:])}</li>" for l in lines) + "</ul>"
    return "".join(f"<p>{esc(l)}</p>" for l in lines if l.strip())


def review_sections() -> set:
    src = CONFIG.read_text(encoding="utf-8")
    block = re.search(r"ownerReviewSections\s*=\s*\{(.*?)\};", src, re.S).group(1)
    return set(re.findall(r"'([a-z]+\.\d+)'", block))


def sections(arb: dict, prefix: str) -> list:
    out, n = [], 1
    while f"{prefix}{n}Title" in arb:
        out.append((n, arb[f"{prefix}{n}Title"], arb[f"{prefix}{n}Body"]))
        n += 1
    return out


def language_block(name: str, lang: str, arb: dict, review: set) -> str:
    prefix, title_key, other_route, other_title_key = DOCS[name]
    version = esc(arb["legalVersion"]).replace("&#123;version}", "{{ config('melai.legal.terms_version') }}")
    parts = [
        f'<article class="card" lang="{lang}" style="max-width:760px;line-height:1.6">',
        f"    <h1>{esc(arb[title_key])}</h1>",
        f'    <p class="muted">{version} · '
        f"<a class=\"link\" href=\"{{{{ route('legal.{name}', ['lang' => '{UI[lang]['switch_lang']}']) }}}}\">"
        f"{UI[lang]['switch']}</a></p>",
    ]
    for n, title, body in sections(arb, prefix):
        parts.append("    <section>")
        parts.append(f"        <h2>{esc(title)}</h2>")
        parts.append(f"        {body_html(body)}")
        if f"{name}.{n}" in review:
            parts.append(f'        <p class="muted" style="color:#91571C">{esc(arb["legalOwnerReview"])}</p>')
        parts.append("    </section>")
    parts.append(
        f"    <p><a class=\"link\" href=\"{{{{ url()->previous() }}}}\">{UI[lang]['back']}</a> · "
        f"<a class=\"link\" href=\"{{{{ route('{other_route}', ['lang' => '{lang}']) }}}}\">{esc(arb[other_title_key])}</a></p>"
    )
    parts.append("</article>")
    return "\n".join(parts)


def page(name: str, arbs: dict, review: set) -> str:
    title_key = DOCS[name][1]
    return "\n".join([
        "{{-- GENERATED by scripts/gen_legal_pages.py from lib/l10n/app_en.arb and app_fil.arb. Do not edit by hand:",
        "     change the .arb text, then run python3 scripts/gen_legal_pages.py. --}}",
        "@extends('layouts.base')",
        f"@section('title', request()->query('lang') === 'fil' ? '{esc(arbs['fil'][title_key])} · Melai Nuts' : '{esc(arbs['en'][title_key])} · Melai Nuts')",
        "@section('content')",
        '<main class="center-page" style="align-items:flex-start">',
        "@if (request()->query('lang') === 'fil')",
        language_block(name, "fil", arbs["fil"], review),
        "@else",
        language_block(name, "en", arbs["en"], review),
        "@endif",
        "</main>",
        "@endsection",
        "",
    ])


def main() -> int:
    arbs = {lang: json.loads(p.read_text(encoding="utf-8")) for lang, p in ARB.items()}
    review = review_sections()
    stale = []
    for name in DOCS:
        target = OUT / f"{name}.blade.php"
        text = page(name, arbs, review)
        current = target.read_text(encoding="utf-8").replace("\r\n", "\n") if target.exists() else ""
        if current != text:
            stale.append(target.relative_to(ROOT).as_posix())
            if "--check" not in sys.argv:
                target.write_text(text, encoding="utf-8", newline="\n")
    if "--check" in sys.argv and stale:
        print("Out of date (run python3 scripts/gen_legal_pages.py): " + ", ".join(stale))
        return 1
    print(("Rewrote: " + ", ".join(stale)) if stale else "Legal pages are up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
