#!/usr/bin/env python3
"""Copies moderation/blocked_words.json (the ONE list to edit) to the places that cannot read it.

    python3 scripts/sync_blocked_words.py          write the generated files
    python3 scripts/sync_blocked_words.py --check  exit 1 if a generated file is out of date (CI)

Writes:
  lib/core/moderation/blocked_words_list.g.dart   the app's copy (Dart cannot read the JSON
                                                  synchronously inside a form validator)
  supabase/repair/sync_blocked_words.sql          run it in the Supabase SQL editor after an edit,
                                                  so the database blocks exactly the same words
  admin/resources/moderation/blocked_words.json   the website's copy when admin/ is deployed alone

The website (PHP and JavaScript) reads the JSON itself: nothing to do there.
"""
import json
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
SRC = os.path.join(ROOT, 'moderation', 'blocked_words.json')
DART = os.path.join(ROOT, 'lib', 'core', 'moderation', 'blocked_words_list.g.dart')
SQL = os.path.join(ROOT, 'supabase', 'repair', 'sync_blocked_words.sql')
# The website's own copy, for deployments of admin/ alone (Railway root directory /admin).
ADMIN_COPY = os.path.join(ROOT, 'admin', 'resources', 'moderation', 'blocked_words.json')
KINDS = ('words', 'roots', 'phrases', 'allow')
KIND_SQL = {'words': 'word', 'roots': 'root', 'phrases': 'phrase', 'allow': 'allow'}
OK_TERM = re.compile(r'^[a-z]+( [a-z]+)*$')


def load() -> dict:
    with open(SRC, encoding='utf-8') as f:
        data = json.load(f)
    out = {'message': str(data.get('message') or 'Please keep your message respectful.')}
    for k in KINDS:
        terms = sorted({' '.join(str(t).strip().lower().split()) for t in data.get(k, []) if str(t).strip()})
        for t in terms:
            if not OK_TERM.match(t) or (k != 'phrases' and ' ' in t):
                sys.exit(f'{SRC}: "{t}" in {k} must be lowercase letters a-z only'
                         + (' (spaces only in phrases)' if k != 'phrases' else ''))
        out[k] = terms
    return out


def dart_str(v: str) -> str:
    return "'" + v.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$') + "'"


def dart(d: dict) -> str:
    def lst(items):
        return '[\n' + ''.join(f"  '{t}',\n" for t in items) + ']'
    return (
        '// GENERATED by scripts/sync_blocked_words.py from moderation/blocked_words.json.\n'
        '// Do not edit by hand: edit the JSON, then run the script.\n'
        '// ignore_for_file: public_member_api_docs\n\n'
        f"const String blockedWordsMessage = {dart_str(d['message'])};\n\n"
        f"const List<String> blockedWordsWords = {lst(d['words'])};\n\n"
        f"const List<String> blockedWordsRoots = {lst(d['roots'])};\n\n"
        f"const List<String> blockedWordsPhrases = {lst(d['phrases'])};\n\n"
        f"const List<String> blockedWordsAllow = {lst(d['allow'])};\n"
    )


def sql_seed(d: dict) -> str:
    """The statements that make the database list equal to the JSON (used by the migration too)."""
    rows = []
    for k in KINDS:
        rows += [f"('{KIND_SQL[k]}', '{t}')" for t in d[k]]
    msg = d['message'].replace("'", "''")
    return (
        'delete from public.moderation_blocked_terms;\n'
        'insert into public.moderation_blocked_terms (kind, term) values\n  '
        + ',\n  '.join(rows) + ';\n'
        f"insert into public.moderation_settings (id, message) values ('default', '{msg}')\n"
        '  on conflict (id) do update set message = excluded.message;\n'
    )


def sql(d: dict) -> str:
    return (
        '-- GENERATED by scripts/sync_blocked_words.py from moderation/blocked_words.json.\n'
        '-- Run in the Supabase SQL editor after editing the list (needs migration\n'
        '-- 20261119030000_blocked_words.sql). Replaces the database copy of the list in one go.\n'
        'begin;\n' + sql_seed(d) + 'commit;\n'
    )


def main() -> int:
    d = load()
    files = {DART: dart(d), SQL: sql(d), ADMIN_COPY: open(SRC, encoding='utf-8').read()}
    stale = []
    for path, content in files.items():
        current = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if current != content:
            stale.append(os.path.relpath(path, ROOT))
            if '--check' not in sys.argv:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, 'w', encoding='utf-8') as f:
                    f.write(content)
    if '--check' in sys.argv:
        if stale:
            print('Out of date (run python3 scripts/sync_blocked_words.py):', ', '.join(stale))
            return 1
        print('Blocked words: generated files are up to date.')
        return 0
    print('Updated: ' + (', '.join(stale) if stale else 'nothing (already up to date)'))
    if any(p.endswith('.sql') for p in stale):
        print('Now run supabase/repair/sync_blocked_words.sql in the Supabase SQL editor.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
