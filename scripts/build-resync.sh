#!/usr/bin/env bash
# =============================================================================
# Melai Nuts — regenerate supabase/repair/20261010_resync_live_database.sql from
# EVERY file in supabase/migrations/ (in order), so "bring an existing project up
# to date" always means "re-run all current migrations" (each one is idempotent
# and runs in its own transaction).
#
#   bash scripts/build-resync.sh            # rewrite the file
#   bash scripts/build-resync.sh --check    # CI: fail if the file is out of date
# =============================================================================
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/supabase/repair/20261010_resync_live_database.sql"
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

{
cat <<'HEAD'
-- =============================================================================
-- Melai Nuts — bring an EXISTING (live) Supabase database up to date
-- =============================================================================
-- GENERATED by scripts/build-resync.sh from every file in supabase/migrations/,
-- in file-name order. Do not edit by hand: change the migration, then run the
-- script (CI fails when this file is out of date).
--
-- WHAT IT DOES
--   Re-runs every migration. Each one is idempotent and runs in its own
--   transaction. No business rows are deleted or overwritten: migrations create
--   structure only (tested by scripts/run-sql-tests.sh, which re-runs them on a
--   database holding real values and checks that nothing changed). The only data
--   changes are those the migrations document (e.g. 20261018000000 carries the old
--   built-in thresholds over ONCE into business_settings, flagged carried_over).
--
-- HOW TO RUN (staging first — see docs/PRODUCTION_RUNBOOK.md)
--   psql "<postgres connection string>" -v ON_ERROR_STOP=1 -f this-file
--   (or Supabase dashboard > SQL Editor > paste > Run). App calls may fail for the
--   few seconds it runs; run it when the shop is quiet.
--
-- NEVER run supabase/schema.sql on a project that already has data: it is for new,
-- empty projects only.
-- =============================================================================

HEAD
for f in "$ROOT"/supabase/migrations/*.sql; do
  printf '\n\n-- >>>>>>>>>> %s <<<<<<<<<<\n' "$(basename "$f")"
  cat "$f"
done
} > "$TMP"

if [ "${1:-}" = "--check" ]; then
  if ! cmp -s "$TMP" "$OUT"; then
    echo "supabase/repair/20261010_resync_live_database.sql is out of date: run bash scripts/build-resync.sh"
    exit 1
  fi
  echo "resync file is up to date"
else
  cp "$TMP" "$OUT"
  echo "wrote $OUT ($(grep -c '^-- >>>>>>>>>>' "$OUT") migrations)"
fi
