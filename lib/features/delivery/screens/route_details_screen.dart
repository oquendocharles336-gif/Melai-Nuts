/// Per-leg breakdown of the run: the estimate saved with it and, when both
/// ends have coordinates, a link to real directions in Google Maps. No
/// directions are generated by the app.
class RouteDetailsScreen extends StatelessWidget {
  final Delivery delivery;

  const RouteDetailsScreen({super.key, required this.delivery});

  /// Google Maps directions between two known points; null when either end
  /// has no coordinates (no directions are made up).
  static Uri? _directions(double? fromLat, double? fromLng, double? toLat, double? toLng) {
    final to = DeliveryMap.point(toLat, toLng);
    if (to == null) return null;
    final from = DeliveryMap.point(fromLat, fromLng);
    return Uri.https('www.google.com', '/maps/dir/', {
      'api': '1',
      if (from != null) 'origin': '${from.latitude},${from.longitude}',
      'destination': '${to.latitude},${to.longitude}',
      'travelmode': 'driving',
    });
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: AppColors.canvas,
      appBar: MelaiAppBar(title: 'Route Details • ${delivery.id}', showBack: true),
      body: SafeArea(
        child: ListView(
          padding: const EdgeInsets.all(AppSpacing.md),
          children: [
            // The run on the map: customer pins in stop order, next stop highlighted.
            RunMapCard(delivery: delivery, height: 220),
            const SizedBox(height: AppSpacing.md),
            Container(
              padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 8),
              decoration: BoxDecoration(color: AppColors.surfaceContainerLow, borderRadius: BorderRadius.circular(20), border: Border.all(color: AppColors.border)),
              child: Row(
                children: [
                  const Icon(Icons.info_outline_rounded, size: 16, color: AppColors.textSecondary),
                  const SizedBox(width: 6),
                  Expanded(
                    child: Text(
                      'Distance and time per leg are the estimate saved with the run. For turn-by-turn directions, open the leg in Google Maps.',
                      style: AppTextStyles.bodySm,
                    ),
                  ),
                ],
              ),
            ),
            const SizedBox(height: AppSpacing.md),
            if (delivery.stops.isEmpty)
              const StateEmptyView(icon: Icons.route_outlined, title: 'This run has no stops.', compact: true),
            for (int i = 0; i < delivery.stops.length; i++)
              Padding(
                padding: const EdgeInsets.only(bottom: 14),
                child: _LegCard(
                  legNumber: i + 1,
                  from: i == 0 ? delivery.branch : delivery.stops[i - 1].customerName,
                  to: delivery.stops[i].customerName,
                  toAddress: delivery.stops[i].address,
                  distanceKm: delivery.stops[i].distanceFromPreviousKm,
                  minutes: delivery.stops[i].travelMinutesFromPrevious,
                  eta: delivery.stops[i].eta,
                  directions: _directions(
                    i == 0 ? delivery.branchLatitude : delivery.stops[i - 1].latitude,
                    i == 0 ? delivery.branchLongitude : delivery.stops[i - 1].longitude,
                    delivery.stops[i].latitude,
                    delivery.stops[i].longitude,
                  ),
                ),
              ),
          ],
        ),
      ),
    );
  }
}

class _LegCard extends StatelessWidget {
  final int legNumber;
  final String from;
  final String to;
  final String toAddress;
  final double distanceKm;
  final int minutes;
  final String eta;
  final Uri? directions;

  const _LegCard({
    required this.legNumber,
    required this.from,
    required this.to,
    required this.toAddress,
    required this.distanceKm,
    required this.minutes,
    required this.eta,
    required this.directions,
  });

  @override
  Widget build(BuildContext context) {
    return Container(
      padding: const EdgeInsets.all(14),
      decoration: BoxDecoration(color: Colors.white, borderRadius: BorderRadius.circular(AppSpacing.radiusMd), border: Border.all(color: AppColors.border), boxShadow: AppShadows.sm),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            children: [
              Container(
                padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 3),
                decoration: BoxDecoration(color: AppColors.primaryContainer, borderRadius: BorderRadius.circular(20)),
                child: Text('LEG $legNumber', style: AppTextStyles.labelSm.copyWith(color: AppColors.primaryDark)),
              ),
              const Spacer(),
              Text('~${distanceKm.toStringAsFixed(1)} km • ~$minutes min', style: AppTextStyles.bodySm),
            ],
          ),
          const SizedBox(height: 6),
          Text('$from → $to', style: AppTextStyles.titleMd),
          Text(toAddress, style: AppTextStyles.bodySm),
          if (eta.isNotEmpty) Text('Est. arrival $eta', style: AppTextStyles.bodySm.copyWith(color: AppColors.primary)),
          const Divider(height: 20),
          if (directions != null)
            OutlinedButton.icon(
              onPressed: () async {
                final ok = await launchUrl(directions!, mode: LaunchMode.externalApplication);
                if (!ok && context.mounted) {
                  ScaffoldMessenger.of(context).showSnackBar(const SnackBar(content: Text('Could not open Google Maps on this device.')));
                }
              },
              icon: const Icon(Icons.directions_rounded, size: 16),
              label: const Text('Directions in Google Maps'),
            )
          else
            Text('No map coordinates for this address, so directions are not available.', style: AppTextStyles.bodySm),
        ],
      ),
    );
  }
}
