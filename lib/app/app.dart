import 'package:flutter/material.dart';
import 'package:flutter_localizations/flutter_localizations.dart';
import '../core/services/locale_controller.dart';
import '../l10n/generated/app_localizations.dart';
import '../core/theme/app_theme.dart';
import 'route_guard.dart';
import 'routes.dart';

/// Root widget of the Melai Nuts Retailing Android app.
class MelaiNutsApp extends StatelessWidget {
  const MelaiNutsApp({super.key});

  @override
  Widget build(BuildContext context) {
    return ValueListenableBuilder<Locale?>(
      valueListenable: LocaleController.instance,
      builder: (context, locale, _) => MaterialApp(
      title: 'Melai Nuts Retailing',
      locale: locale,
      // English + Filipino (lib/l10n/*.arb, generated by `flutter gen-l10n` /
      // `flutter pub get`). The global delegates translate Material's own labels
      // (date pickers, "Back" tooltips, ...).
      localizationsDelegates: const [
        AppLocalizations.delegate,
        GlobalMaterialLocalizations.delegate,
        GlobalWidgetsLocalizations.delegate,
        GlobalCupertinoLocalizations.delegate,
      ],
      supportedLocales: AppLocalizations.supportedLocales,
      localeListResolutionCallback: (preferred, supported) {
        for (final l in preferred ?? const <Locale>[]) {
          if (LocaleController.supportedCodes.contains(l.languageCode)) return Locale(l.languageCode);
          if (l.languageCode == 'tl') return const Locale('fil'); // Tagalog phones
        }
        return const Locale('en');
      },
      debugShowCheckedModeBanner: false,
      theme: AppTheme.light(),
      initialRoute: AppRoutes.splash,
      routes: AppRoutes.routes,
      onGenerateRoute: (settings) => AppRoutes.onGenerateRoute(settings),
      onUnknownRoute: (settings) => MaterialPageRoute<dynamic>(
        settings: settings,
        builder: (_) => const UnavailableRouteScreen(),
      ),
      ),
    );
  }
}
